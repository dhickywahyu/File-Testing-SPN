def text_to_columns(text, spacing=1):
    """Render teks menjadi list kolom byte (font 5x7, baris 0..6)."""
    cols = []
    for ch in text:
        code = ord(ch)
        if code < 0x20 or code > 0x7E:
            code = ord("?")
        i = (code - 0x20) * 5
        cols.extend(_FONT[i:i + 5])
        cols.extend([0] * spacing)
    return cols


def _map_pixel(r, c, rotation, flip):
    """Petakan piksel blok 8x8 (baris r, kolom c) -> (digit 0..7, bit 0..7)."""
    if flip:
        c = 7 - c
    if rotation == 90:
        return c, r
    if rotation == 180:
        return 7 - r, c
    if rotation == 270:
        return 7 - c, 7 - r
    return r, 7 - c


class Max7219:
    def __init__(self, gpio, clk, cs, din, modules=4):
        self.g = gpio
        self.clk, self.cs, self.din, self.n = clk, cs, din, modules
        for p, v in ((clk, 0), (cs, 1), (din, 0)):
            gpio.setup_output(p, v)
        self.rotation, self.flip, self.reverse = 90, False, False

    # -- level rendah -------------------------------------------------------
    def _shift_byte(self, b):
        w, clk, din = self.g.write, self.clk, self.din
        for i in range(7, -1, -1):
            w(din, (b >> i) & 1)
            w(clk, 1)
            w(clk, 0)

    def _send(self, pairs):
        """pairs[0] dikirim pertama -> berakhir di modul paling JAUH dari DIN."""
        self.g.write(self.cs, 0)
        for reg, data in pairs:
            self._shift_byte(reg)
            self._shift_byte(data)
        self.g.write(self.cs, 1)

    def write_all(self, reg, data):
        self._send([(reg, data)] * self.n)

    # -- API ---------------------------------------------------------------
    def init(self, brightness):
        # Urutan aman: display di-shutdown dulu, isi RAM digit (acak saat power-on) dihapus,
        # baru display dinyalakan -> tidak ada LED acak yang menyala saat start.
        # Register Display-Test (0x0F) SELALU 0: mode itu menyalakan semua LED pada kecerahan
        # maksimum (~1,27 A untuk 4 modul) dan terbukti merusak AMS1117 -> sengaja tidak disediakan.
        self.write_all(REG_SHUTDOWN, 0)
        self.write_all(REG_DISPLAYTEST, 0)
        self.write_all(REG_SCANLIMIT, 7)
        self.write_all(REG_DECODE, 0)
        self.write_all(REG_INTENSITY, max(0, min(15, int(brightness))))
        for d in range(1, 9):
            self.write_all(d, 0)
        self.write_all(REG_SHUTDOWN, 1)

    def set_brightness(self, v):
        self.write_all(REG_INTENSITY, max(0, min(15, int(v))))

    def show(self, fb):
        mods = []
        for m in range(self.n):
            digits = [0] * 8
            base = m * 8
            for c in range(8):
                col = fb[base + c]
                if not col:
                    continue
                for r in range(8):
                    if (col >> r) & 1:
                        d, b = _map_pixel(r, c, self.rotation, self.flip)
                        digits[d] |= 1 << b
            mods.append(digits)
        if self.reverse:
            mods.reverse()
        for d in range(8):
            self._send([(d + 1, mods[k][d]) for k in range(self.n)])

    def clear(self):
        self.show([0] * (self.n * 8))


class SimMax7219(Max7219):
    """Tidak mengirim apa pun; meniru waktu transfer bit-bang (~6 ms)."""

    def __init__(self, *a, **k):
        self.n = k.get("modules", 4)
        self.rotation, self.flip, self.reverse = 90, False, False

    def _send(self, pairs):
        time.sleep(0.0007)
